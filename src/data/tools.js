const NEWEST_DATE_ADDED = Date.UTC(2026, 9, 18) // 2026-10-18
const DAY_MS = 86_400_000
const DATE_ADDED_STEP_DAYS = 4

function deriveDateAdded(index, count) {
  const daysFromNewest = (count - 1 - index) * DATE_ADDED_STEP_DAYS
  return new Date(NEWEST_DATE_ADDED - daysFromNewest * DAY_MS).toISOString().slice(0, 10)
}

